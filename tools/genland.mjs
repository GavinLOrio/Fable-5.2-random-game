// Rasterises real coastlines (Natural Earth 1:50m via world-atlas) into a run-length encoded land mask
// covering the Mediterranean basin. Output: rome/src/gen/land.js
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

export const LON0 = -10, LON1 = 37, LAT0 = 29.5, LAT1 = 48;
const PXD = 30;                         // pixels per degree of longitude
const KX = 200, KZ = 254;               // world units per degree (lon, lat)
const W = Math.round((LON1 - LON0) * PXD), H = Math.round((LAT1 - LAT0) * PXD * KZ / KX);

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const rings = [];
const add = (poly) => { for (const r of poly) rings.push(r); };
for (const f of land.features || [land]) {
  const g = f.geometry;
  if (g.type === 'Polygon') add(g.coordinates); else for (const p of g.coordinates) add(p);
}
// keep only rings touching the window
const use = rings.filter((r) => { let a = 1e9, b = -1e9, c = 1e9, d = -1e9; for (const [x, y] of r) { a = Math.min(a, x); b = Math.max(b, x); c = Math.min(c, y); d = Math.max(d, y); } return b > LON0 - 1 && a < LON1 + 1 && d > LAT0 - 1 && c < LAT1 + 1; });
const mask = new Uint8Array(W * H);
for (let j = 0; j < H; j++) {
  const lat = LAT1 - (j + 0.5) / H * (LAT1 - LAT0);
  const xs = [];
  for (const r of use) for (let i = 0; i < r.length - 1; i++) {
    const [x0, y0] = r[i], [x1, y1] = r[i + 1];
    if ((y0 <= lat && y1 > lat) || (y1 <= lat && y0 > lat)) xs.push(x0 + (lat - y0) / (y1 - y0) * (x1 - x0));
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const i0 = Math.max(0, Math.ceil((xs[k] - LON0) * PXD - 0.5)), i1 = Math.min(W - 1, Math.floor((xs[k + 1] - LON0) * PXD - 0.5));
    for (let i = i0; i <= i1; i++) mask[j * W + i] = 1;
  }
}
// RLE: alternating run lengths starting with water, varint encoded
const bytes = [];
let cur = 0, run = 0;
const push = (n) => { while (n >= 128) { bytes.push((n & 127) | 128); n >>>= 7; } bytes.push(n); };
for (let i = 0; i < mask.length; i++) { if (mask[i] === cur) run++; else { push(run); cur = mask[i]; run = 1; } }
push(run);
const b64 = Buffer.from(bytes).toString('base64');
writeFileSync('rome/src/gen/land.js', `// Generated by tools/genland.mjs from Natural Earth 1:50m land polygons (public domain). Do not edit.\nexport const LAND = { w: ${W}, h: ${H}, lon0: ${LON0}, lon1: ${LON1}, lat0: ${LAT0}, lat1: ${LAT1}, kx: ${KX}, kz: ${KZ}, rle: '${b64}' };\n`);
let n = 0; for (const v of mask) n += v;
console.log(W, H, 'land frac', (n / mask.length).toFixed(3), 'bytes', bytes.length);
// ascii preview
let s = ''; for (let j = 0; j < H; j += 16) { for (let i = 0; i < W; i += 8) s += mask[j * W + i] ? '#' : '.'; s += '\n'; } console.log(s);
